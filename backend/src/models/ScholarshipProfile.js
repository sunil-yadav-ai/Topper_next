import mongoose from "mongoose";

const scholarshipProfileSchema = new mongoose.Schema({
  user: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true, unique: true, index: true },
  fullName: { type: String, trim: true, maxlength: 100, default: "" },
  dateOfBirth: { type: Date, default: null },
  gender: { type: String, enum: ["", "female", "male", "other", "prefer_not_to_say"], default: "" },
  state: { type: String, trim: true, maxlength: 100, default: "" },
  district: { type: String, trim: true, maxlength: 100, default: "" },
  domicileState: { type: String, trim: true, maxlength: 100, default: "" },
  category: { type: String, enum: ["", "general", "sc", "st", "obc", "ews", "other"], default: "" },
  minorityStatus: { type: String, enum: ["", "yes", "no"], default: "" },
  disabilityStatus: { type: String, enum: ["", "none", "yes"], default: "" },
  educationLevel: { type: String, trim: true, maxlength: 120, default: "" },
  courseName: { type: String, trim: true, maxlength: 150, default: "" },
  currentAcademicYear: { type: String, trim: true, maxlength: 30, default: "" },
  collegeName: { type: String, trim: true, maxlength: 200, default: "" },
  universityRegistrationNumber: { type: String, trim: true, maxlength: 100, default: "" },
  tenthPassingYear: { type: Number, min: 1950, max: 2100, default: null },
  tenthSchoolState: { type: String, trim: true, maxlength: 100, default: "" },
  tenthPercentage: { type: Number, min: 0, max: 100, default: null },
  twelfthPassingYear: { type: Number, min: 1950, max: 2100, default: null },
  twelfthSchoolState: { type: String, trim: true, maxlength: 100, default: "" },
  class12Passed: { type: Boolean, default: null },
  twelfthPercentage: { type: Number, min: 0, max: 100, default: null },
  currentSemesterPercentage: { type: Number, min: 0, max: 100, default: null },
  previousExamPercentage: { type: Number, min: 0, max: 100, default: null },
  annualFamilyIncome: { type: Number, min: 0, default: null },
  undergraduateFirstYear: { type: String, enum: ["", "yes", "no"], default: "" },
  admissionType: { type: String, enum: ["", "regular", "distance"], default: "" },
  recognizedInstitution: { type: String, enum: ["", "yes", "no"], default: "" },
  incomeCertificateAvailable: { type: Boolean, default: false },
  bplStatus: { type: Boolean, default: false },
  residenceType: { type: String, enum: ["", "hostel", "day_scholar"], default: "" },
  domicileCertificateAvailable: { type: Boolean, default: false },
  aadhaarAvailable: { type: Boolean, default: false },
  bankAccountAvailable: { type: Boolean, default: false },
  netJrfQualified: { type: Boolean, default: null },
  researchRegistrationWithinStipulatedPeriod: { type: Boolean, default: null },
  nationality: { type: String, enum: ["", "Indian", "Other"], default: "" },
  firstYearPostgraduate: { type: String, enum: ["", "yes", "no"], default: "" },
  regularFullTime: { type: String, enum: ["", "yes", "no"], default: "" },
  recognizedPgDegree: { type: String, enum: ["", "yes", "no"], default: "" },
  postgraduateComponent: { type: String, enum: ["", "yes", "no", "not_applicable"], default: "" },
  profileCompletedAt: { type: Date, default: null },
}, { timestamps: true });

const ScholarshipProfile =
  mongoose.models.ScholarshipProfile ||
  mongoose.model("ScholarshipProfile", scholarshipProfileSchema);
export default ScholarshipProfile;
